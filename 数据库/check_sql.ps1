# =============================================
# 校园活动管理系统 - SQL Server 服务状态检查
# =============================================
# 用途: 快速检查本机 SQL Server 相关服务的运行状态
# 用法: 在 PowerShell 中执行 .\check_sql.ps1
# =============================================

# 筛选名称包含 "SQL" 的服务，显示名称和运行状态
Get-Service | Where-Object { $_.Name -like '*SQL*' } | Format-Table Name, Status
